// Rebuild reference data from a saved public wiki HTML; never contacts the server.
// Usage: node tools/sync-rune-reference.mjs <wiki.html> <composer-images-directory>
import fs from 'node:fs';
import path from 'node:path';
import vm from 'node:vm';
const [wikiPath, imagesPath] = process.argv.slice(2);
if (!wikiPath || !imagesPath) throw new Error('Expected wiki HTML and image directory');
const root = path.resolve(import.meta.dirname, '..');
const publicDir = path.join(root, 'public');
const ctx = vm.createContext({ window: {} });
vm.runInContext(fs.readFileSync(path.join(publicDir, 'rune-wiki-data.js'), 'utf8'), ctx);
const existing = ctx.window.RuneWikiData;
const clean = s => s.replace(/<br\s*\/?\s*>/gi, '\n').replace(/<[^>]*>/g, '').replace(/&amp;/g, '&').replace(/&#(?:39|x27);/g, "'").replace(/&quot;/g, '"').replace(/&nbsp;/g, ' ').replace(/[ \t\r]+/g, ' ').replace(/ *\n */g, '\n').trim();
const html = fs.readFileSync(wikiPath, 'utf8');
const tables = [...html.matchAll(/<table\b[^>]*>[\s\S]*?<\/table>/g)].map(m => [...m[0].matchAll(/<tr\b[^>]*>([\s\S]*?)<\/tr>/g)].map(row => [...row[1].matchAll(/<(?:th|td)\b[^>]*>([\s\S]*?)<\/(?:th|td)>/g)].map(cell => clean(cell[1]))));
const data = {};
for (const table of tables.slice(1, 5)) {
  const headers = table[0];
  for (const cells of table.slice(1)) {
    if (cells.length !== headers.length) throw new Error('Unexpected wiki row: ' + cells[0]);
    cells[0] = cells[0].replace(/^24px\s*/, '');
    const id = Object.keys(existing).find(id => existing[id].name === cells[0]);
    if (!id) throw new Error('Unknown rune name: ' + cells[0]);
    data[id] = { name: cells[0], type: cells[1], base: cells[2], effects: Object.fromEntries(headers.slice(3).map((h, i) => [h, cells[i + 3]])) };
  }
}
if (Object.keys(data).length !== 46) throw new Error('Expected 46 rune records');
const enchantments = {};
for (const table of tables.slice(6, 9)) {
  for (const cells of table.slice(1)) enchantments[cells[0]] = Object.fromEntries(table[0].slice(1).map((h, i) => [h, cells[i + 1] || '']));
}
const aliases = { 'Flame-Poison Seal': 'Flamenox Seal', 'Frost-Thunder Seal': 'Frostshock Seal', 'Rotating SPD Up': 'Spin SPD Up', 'Ricocheting Strike': 'Ricochet Strike', 'Flame-Poison Touch': 'Flamenox Touch', 'Frost-Thunder Touch': 'Frostshock Touch' };
for (const rune of Object.values(data)) {
  rune.enchantments = enchantments[aliases[rune.name] || rune.name] || {};
  rune.sharedEnchantments = enchantments['All ' + rune.type] || {};
}
const provenance = { url: 'https://archero-2.game-vault.net/wiki/Runes', snapshot: 'https://web.archive.org/web/20260316234950/https://archero-2.game-vault.net/wiki/Runes', snapshotDate: '2026-03-16', lastEdited: '2026-03-10', note: 'Reference text, not a guarantee that every combat effect is implemented.' };
fs.writeFileSync(path.join(publicDir, 'rune-wiki-data.js'), '// Public wiki snapshot, archived 2026-03-16. Generated by tools/sync-rune-reference.mjs.\nwindow.RuneWikiSource = Object.freeze(' + JSON.stringify(provenance, null, 2) + ');\nwindow.RuneWikiData = Object.freeze(' + JSON.stringify(data, null, 2) + ');\n');
const imageAliases = { Revive: 'rune_valkyrie', Rabbit_s_Foot: 'rabbits_foot', Sprite_s_Awe: 'sprites_awe', Spin_SPD_Up: 'rotating_spd_up', Ricochet_Strike: 'ricocheting_strike', Flamenox_Seal: 'rune_flame', Frostshock_Seal: 'rune_frost', Circle: 'ability_circle', 'Frost-Thunder_Touch': 'rune_thunder' };
const files = fs.readdirSync(imagesPath);
const candidates = {};
for (const file of files) {
  const m = file.match(/^Rune_Skill_(Bless|Grow|S|Skill)_(\d{3})([A-Za-z][A-Za-z_-]*)_[a-f0-9]{6}\.png$/);
  if (!m) continue;
  const id = imageAliases[m[3]] || m[3].toLowerCase().replaceAll('-', '_');
  if (!data[id]) throw new Error('Unknown named image: ' + file);
  const key = m[1] + '_' + m[2];
  const stat = fs.statSync(path.join(imagesPath, file));
  if (!candidates[key] || stat.mtimeMs > candidates[key].mtimeMs) candidates[key] = { id, file, mtimeMs: stat.mtimeMs };
}
const outDir = path.join(publicDir, 'assets/runes');
fs.mkdirSync(outDir, { recursive: true });
const images = {}, manifest = {};
for (const [key, entry] of Object.entries(candidates).sort()) {
  // Both 007 and 009 are explicitly named Star_of_Fury by the user. Preserve both;
  // never silently relabel 007 as Arrow Rain.
  const slug = entry.id === 'star_of_fury' ? entry.id + '-' + key.toLowerCase() : entry.id;
  const dest = slug + '.png';
  fs.copyFileSync(path.join(imagesPath, entry.file), path.join(outDir, dest));
  manifest[key] = { id: entry.id, source: entry.file, asset: 'assets/runes/' + dest };
  images[entry.id] = 'assets/runes/' + dest;
}
// Remove only stale assets from the interrupted attempt; keep both labelled variants.
const allowed = new Set(Object.values(manifest).map(x => path.basename(x.asset)));
for (const file of fs.readdirSync(outDir)) if (file.endsWith('.png') && !allowed.has(file)) fs.unlinkSync(path.join(outDir, file));
fs.writeFileSync(path.join(publicDir, 'rune-wiki-images.js'), '// Exact user-labelled images. Arrow Rain and Echo Scythe have no unambiguous supplied image.\nwindow.RuneWikiImages = Object.freeze(' + JSON.stringify(images, null, 2) + ');\nwindow.RuneImageManifest = Object.freeze(' + JSON.stringify(manifest, null, 2) + ');\n');
console.log(JSON.stringify({ runes: Object.keys(data).length, suppliedImages: Object.keys(manifest).length, mappedRunes: Object.keys(images).length, fallback: Object.keys(data).filter(id => !images[id]) }));
