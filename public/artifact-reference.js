  const aliases = { 'Magic Carpet': 'Margic Carpet' };
  const normalizeName = name => String(name).replace(/[’']/g, '').replace(/[^a-z0-9]/gi, '').toLowerCase();
  const artSlugs = { "Damocles' Sword": 'Damocles_Sword' };
  const byName = new Map(reference.artifacts.map(row => [normalizeName(row.name), row]));
  function applyCatalog(catalog) {
    for (const artifact of catalog) {
      const row = byName.get(normalizeName(aliases[artifact.wikiName] || artifact.wikiName));
      if (!row) throw new Error('Thiếu tham chiếu thánh vật: ' + artifact.id);
      artifact.reference = row;
      artifact.wikiName = row.name;
      artifact.specialStatText = row.specialStats;
      artifact.source = row.obtain === null ? 'Wiki không nêu nơi nhận' : row.obtain;
      artifact.desc = row.description;
      // Cột Base Stats của Margic Carpet ghi Gold in Gold Cave, không ghi ATK/HP.
      // Giữ nguyên chỉ số game cũ; không suy diễn đó là dữ liệu ATK/HP của wiki.
      const base = /^ATK \+(\d+) & HP \+(\d+)$/.exec(row.baseStats);
      if (base) { artifact.baseAtk = Number(base[1]); artifact.baseHp = Number(base[2]); }
      artifact.artPath = ['Quiet Quill', 'Voidblade'].includes(row.name) ? null :
        'assets/artifacts/' + (artSlugs[row.name] || row.name.replace(/'/g, '_').replace(/ /g, '_')) + '.png';
    }
    return catalog;
  }
  function escapeHtml(value) {
    return String(value).replace(/[&<>"']/g, char => ({ '&':'&amp;', '<':'&lt;', '>':'&gt;', '"':'&quot;', "'":'&#39;' })[char]);
  }
  function renderIcon(artifact) {
    const fallback = '<span class="artifact-art-fallback" aria-hidden="true">' + escapeHtml(artifact.icon || '🏺') + '</span>';
    if (!artifact.artPath) return fallback;
    return '<span class="artifact-art">' + fallback + '<img src="' + escapeHtml(artifact.artPath) +
      '" alt="' + escapeHtml(artifact.wikiName) + '" loading="lazy" decoding="async" onerror="this.hidden=true" onload="this.previousElementSibling.hidden=true"></span>';
  }
  root.ArtifactReference = { reference, applyCatalog, renderIcon, escapeHtml };
